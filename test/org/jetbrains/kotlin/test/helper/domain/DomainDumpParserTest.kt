package org.jetbrains.kotlin.test.helper.domain

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue

class DomainDumpParserTest {
    @Test
    fun parsesDomainEntriesWithMultipleLabelsAndIgnoredPaths() {
        val dump = parseDomainDump(
            """
            #### Domain dump
            This dump is generated by DomainsDumpTest.kt

            CompilerInfrastructure:
             - compiler/cli/src

            CompilerInfrastructure, Gradle:
             - compiler/build-tools/kotlin-build-statistics

            Unknown:
             - misc/file.kt
            """.trimIndent(),
        )

        assertEquals(
            listOf(
                DomainDumpEntry(setOf(Domain.of("CompilerInfrastructure")), RepositoryPath.of("compiler/cli/src")),
                DomainDumpEntry(
                    setOf(Domain.of("CompilerInfrastructure"), Domain.of("Gradle")),
                    RepositoryPath.of("compiler/build-tools/kotlin-build-statistics"),
                ),
                DomainDumpEntry(setOf(Domain.of("Unknown")), RepositoryPath.of("misc/file.kt")),
            ),
            dump.entries,
        )
        assertEquals(
            mapOf(
                Domain.of("CompilerInfrastructure") to setOf(
                    RepositoryPath.of("compiler/cli/src"),
                    RepositoryPath.of("compiler/build-tools/kotlin-build-statistics"),
                ),
                Domain.of("Gradle") to setOf(
                    RepositoryPath.of("compiler/build-tools/kotlin-build-statistics"),
                ),
                Domain.of("Unknown") to setOf(
                    RepositoryPath.of("misc/file.kt"),
                ),
            ),
            dump.paths,
        )
    }

    @Test
    fun normalizesRepositoryPathsAndDomainNames() {
        assertEquals("compiler/cli/src", RepositoryPath.of("  compiler\\cli\\src  ").relativePathString)
        assertEquals(RepositoryPath.of("compiler/cli/src"), RepositoryPath.of("compiler\\cli\\src"))
        assertEquals("CompilerInfrastructure", Domain.of("  CompilerInfrastructure  ").name)
    }

    @Test
    fun detectsDumpChangesAtOldNewAndAncestorPaths() {
        val dumpPath = "/project/repo/domains.dump.txt"

        assertTrue(isDumpPathAffected(dumpPath, listOf(dumpPath)))
        assertTrue(isDumpPathAffected(dumpPath, listOf("/project/repo")))
        assertTrue(isDumpPathAffected(dumpPath, listOf("/project/repo/renamed.txt", dumpPath)))
        assertFalse(isDumpPathAffected(dumpPath, listOf("/project/other.txt")))
    }
}